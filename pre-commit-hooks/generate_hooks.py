"""Generate '.pre-commit-hooks.yaml' from '.pre-commit-config.yaml'
"""

from __future__ import annotations

import argparse
import shlex
import tomllib
from pathlib import Path
from typing import TYPE_CHECKING

import yaml
from pre_commit.store import Store

if TYPE_CHECKING:
    from typing import Any

    # One hook entry of a .pre-commit-config.yaml / .pre-commit-hooks.yaml
    Hook = dict[str, Any]

ROOT = Path(__file__).resolve().parent.parent
HEADER = """\
# GENERATED by pre-commit-hooks/generate_hooks.py from .pre-commit-config.yaml.
# Do not edit; run the generator instead.
#
# Consumers can override the hooks' arguments in their own .pre-commit-config.yaml, via
# either `args:` or `entry:`. Changing `entry:` is highly discouraged, and note that
# changing `args:` replaces the default `args:` completely, rather than appending to them.
#
#   - repo: https://github.com/duatic/duatic_devtools
#     rev: <tag>
#     hooks:
#       - id: black
#       - id: codespell
#         args: [--ignore-words-list=foo]
"""


def install_dependencies(language: str, repo: str, rev: str) -> list[str]:
    """Dependencies that install the hook's own repository, as pre-commit would do it itself.

    :param language: ``language`` of the hook
    :param repo: URL of the repository that provides the hook
    :param rev: tag or revision of the repository
    :returns: dependencies to put in front of the other ``additional_dependencies``; empty for
        languages that need nothing
    """
    if language == "python":
        # pip install of the repository at `rev`
        return [f"git+{repo}@{rev}"]

    if language == "golang":
        # `go install ./...` in the repository: every main package of the module
        module = repo.split("://", 1)[-1].rstrip("/")
        return [f"{module}/...@{rev}"]

    return []


# Multi-line strings as literal blocks (|-) instead of quoted strings. PyYAML falls back to a quoted
# string by itself where a block is not possible (trailing spaces, tabs, non-ASCII, ...).
yaml.add_representer(
    str,
    lambda dumper, text: dumper.represent_scalar(
        "tag:yaml.org,2002:str", text, style="|" if "\n" in text else None
    ),
    Dumper=yaml.SafeDumper,
)

# Mappings always in block style: `default_flow_style=None` would write a hook whose values are
# all plain as `{id: ..., name: ...}`, but only lists of plain values should be `[a, b]`
yaml.add_representer(
    dict,
    lambda dumper, data: dumper.represent_mapping("tag:yaml.org,2002:map", data, flow_style=False),
    Dumper=yaml.SafeDumper,
)


def use_packaged_clang_format(hook: Hook) -> None:
    """Turn the clang-format hook into our wrapper, which installs our ``.clang-format``.

    The upstream hook would read the ``.clang-format`` of the consumer's repository. The wrapper
    copies ours (of the same revision as the hook) into the consumer's repository root first.

    :param hook: the hook to change in place
    """
    hook["entry"] = "duatic-clang-format --install-style-file"

    # The wrapper sets the style itself, and upstream `-style=file` in `args` is redundant
    hook["args"] = [arg for arg in hook.get("args", []) if arg != "-style=file"]

    # Also run on the files that decide the style, to install or restore it
    hook.pop("types_or", None)  # Remove to avoid style files to be removed
    hook["files"] = rf"({hook['files']})|^\.clang-format$|^\.pre-commit-config\.yaml$"


def remote_hook(hook: Hook, repo: str, rev: str, store: Store) -> Hook:
    """Upstream definition of the hook, overridden by what the configuration sets.

    :param hook: the hook as configured in .pre-commit-config.yaml
    :param repo: URL of the repository that provides the hook
    :param rev: tag or revision of the repository
    :param store: pre-commit's cache, used to clone the repository
    :returns: the hook as it is written to .pre-commit-hooks.yaml
    """
    manifest = Path(store.clone(repo, rev)) / ".pre-commit-hooks.yaml"
    upstream = next(h for h in yaml.safe_load(manifest.read_text()) if h["id"] == hook["id"])

    # Everything of the upstream hook, with the keys of the configuration on top
    out: Hook = {**upstream, **hook}

    # The dependencies of the upstream hook and of the configuration come after the install of the
    # repository itself
    extra = list(upstream.get("additional_dependencies", []))
    extra += hook.get("additional_dependencies", [])
    dependencies = install_dependencies(out["language"], repo, rev) + extra
    if dependencies:
        out["additional_dependencies"] = dependencies

    if out["id"] == "clang-format":
        use_packaged_clang_format(out)
    return out


def local_hook(hook: Hook, scripts: set[str]) -> Hook:
    """Local hooks are exported as they are; our own console scripts become python hooks.

    :param hook: the hook as configured in .pre-commit-config.yaml
    :param scripts: names of the console scripts that this repository installs
    :returns: the hook as it is written to .pre-commit-hooks.yaml
    """
    out: Hook = dict(hook)

    if shlex.split(out["entry"])[0] in scripts:
        out["language"] = "python"
    return out


def build_manifest() -> list[Hook]:
    """All hooks of the configuration, in the format of a .pre-commit-hooks.yaml.

    :returns: the hooks, in the order of the configuration
    """
    config = yaml.safe_load((ROOT / ".pre-commit-config.yaml").read_text())
    store = Store()

    # Console scripts that this repository installs (the entries of our own hooks)
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    scripts = set(project.get("scripts", {}))

    hooks: list[Hook] = []
    for repo in config["repos"]:
        for hook in repo["hooks"]:
            if repo["repo"] == "local":
                hooks.append(local_hook(hook, scripts))
            else:
                hooks.append(remote_hook(hook, repo["repo"], repo["rev"], store))
    return hooks


def main() -> None:
    """Write .pre-commit-hooks.yaml from .pre-commit-config.yaml."""
    argparse.ArgumentParser(description=__doc__).parse_args()

    # default_flow_style=None: lists of plain values as `[a, b]`
    manifest = yaml.safe_dump(build_manifest(), sort_keys=False, width=100, default_flow_style=None)
    text = HEADER + "\n" + manifest
    (ROOT / ".pre-commit-hooks.yaml").write_text(text)


if __name__ == "__main__":
    main()
